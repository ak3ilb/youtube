func TestClassifyPlayabilityFailure(t *testing.T) {
	cases := map[string]string{
		"ANDROID: LOGIN_REQUIRED (Sign in to confirm your age)": "AUTH_REQUIRED",
		"ANDROID: ERROR (This video is private)":                "PRIVATE_VIDEO",
		"ANDROID: ERROR (Video unavailable)":                    "VIDEO_UNAVAILABLE",
		"ANDROID: RATE_LIMITED: YouTube rate-limited":           "RATE_LIMITED",
	}
	for attempt, wantCode := range cases {
		err := classifyPlayabilityFailure("x", []string{attempt})
		if err.Code != wantCode {
			t.Errorf("classify(%q) = %s, want %s", attempt, err.Code, wantCode)
		}
	}
}
