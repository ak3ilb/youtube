function pickResult(
  track: CaptionTrack,
  source: TranscriptSource,
  warnings: string[] = [],
): PickCaptionResult {
  return {
    track,
    captionUrl: trackBaseUrl(track),
    translatedFrom: "",
    source,
    warnings,
    resolvedLang: track.languageCode,
  };
}

function matchLang(tracks: CaptionTrack[], want: string): PickCaptionResult | null {
  const target = want.toLowerCase();
  let exactAsr: CaptionTrack | null = null;
  let prefix: CaptionTrack | null = null;
  let baseMatch: CaptionTrack | null = null;
  for (const track of tracks) {
    const code = track.languageCode.toLowerCase();
    if (code === target && !track.isAutoGenerated) {
      return pickResult(track, "manual");
    }
    if (code === target && exactAsr === null) {
      exactAsr = track;
    } else if (code.startsWith(target + "-") && prefix === null) {
      prefix = track;
    } else if (langBase(code) === target && baseMatch === null) {
      baseMatch = track;
    } else if (langBase(target) === code && baseMatch === null) {
      // requested "en-US", available "en"
      baseMatch = track;
    }
  }
  const pick = exactAsr ?? prefix ?? baseMatch;
  if (pick === null) {
    return null;
  }
  return pickResult(pick, sourceOf(pick));
}

function altTranslateUrls(base: CaptionTrack, target: string): string[] {
  return trackAltUrls(base).map((u) => withTranscriptLang(u, target));
}

/**
 * Selects the best track for a language preference chain. Order per requested
 * entry: exact manual > exact ASR > regional variant > base-of-regional. Then
 * auto-translate from any translatable track. Then the first available track
 * (fallback) unless strict.
 */
export function pickCaptionTrack(
  tracks: CaptionTrack[],
  lang: string | undefined,
  strict: boolean,
): PickCaptionResult {
  if (tracks.length === 0) {
    throw new ExtractError({
      code: "NO_CAPTIONS",
      message:
        "This video has no caption tracks (the uploader disabled them or YouTube has not generated any)",
    });
  }
  const chain = parseLangChain(lang);
  if (chain.length === 0) {
    for (const track of tracks) {
      if (!track.isAutoGenerated) {
        return pickResult(track, "manual");
      }
    }
    return pickResult(tracks[0]!, sourceOf(tracks[0]!));
  }

  const available = tracks.map((t) => t.languageCode);

  for (const want of chain) {
    const result = matchLang(tracks, want);
    if (result !== null) {
      return result;
    }
  }

  // Strict mode: never invent a translate/fallback track.
  if (strict) {
    throw new ExtractError({
      code: "LANGUAGE_NOT_AVAILABLE",
      message: `No caption track for language "${lang ?? ""}"; available languages: ${available.join(", ")}`,
      details: { requested: lang ?? "", available },
    });
  }

  // Auto-translate from the first translatable track to the first requested lang.
  const target = chain[0]!;
  for (const track of tracks) {
    if (!track.isTranslatable) {
      continue;
    }
    const url = withTranscriptLang(trackBaseUrl(track), target);
    return {
      track: {
        languageCode: target,
        name: track.name,
        isAutoGenerated: true,
        isTranslatable: true,
        baseUrl: url,
        altUrls: altTranslateUrls(track, target),
        sourceClient: track.sourceClient,
      },
      captionUrl: url,
      translatedFrom: track.languageCode,
      source: "translated",
      resolvedLang: target,
      warnings: [
        `No native "${target}" track; using YouTube auto-translate from "${track.languageCode}"`,
      ],
    };
  }

  // Best-effort: serve whatever exists.
  let fallback = tracks[0]!;
  for (const track of tracks) {
    if (!track.isAutoGenerated) {
      fallback = track;
      break;
    }
  }
  return {
    ...pickResult(fallback, "fallback"),
    warnings: [`Requested "${lang ?? ""}" unavailable; falling back to "${fallback.languageCode}"`],
  };
}

export function enrichSegments(segments: TranscriptSegment[]): TranscriptSegment[] {
  return segments.map((s) => {
    let end = s.end ?? 0;
    if (end <= 0) {
      end = s.start + s.duration;
    }
    if (end < s.start) {
      end = s.start;
    }
    let words: TranscriptWord[] | undefined;
    if (s.words && s.words.length > 0) {
      words = s.words.map((w) => ({ ...w, timestamp: formatTimestamp(w.start) }));
    }
    return {
      text: s.text,
      start: s.start,
      duration: end - s.start,
      end,
      timestamp: formatTimestamp(s.start),
      timestampEnd: formatTimestamp(end),
      words,
    };
  });
}

/** Reports whether text already finishes a sentence/cue cleanly. */
export function sentenceEnd(text: string): boolean {
  const trimmed = text.trim();
  if (trimmed === "") {
    return false;
  }
  const runes = [...trimmed];
  const last = runes[runes.length - 1]!;
  switch (last) {
    case ".":
    case "!":
    case "?":
    case "।":
    case "؟":
    case "…":
    case "♪":
      return true;
    case "]": // e.g. [संगीत] / [music]
      return true;
    default:
      return false;
  }
}

/**
 * Joins YouTube ASR's mid-phrase cue fragments into readable sentences.
 * Official timedtext is already complete; ASR chops speech into ~2-4s windows
 * that often end mid-sentence.
 */
export function mergeASRSegments(segments: TranscriptSegment[]): TranscriptSegment[] {
  if (segments.length <= 1) {
    return enrichSegments(segments);
  }
  const enriched = enrichSegments(segments);
  const maxGap = 1.75;
  const maxDuration = 45.0;
  const maxChars = 500;

  const out: TranscriptSegment[] = [];
  let cur = { ...enriched[0]! };
  for (let i = 1; i < enriched.length; i++) {
    const next = enriched[i]!;
    const span = next.end - cur.start;
    const chars = [...cur.text].length + 1 + [...next.text].length;
    // ASR cues often overlap in time (rolling windows) while carrying the NEXT
    // phrase only — allow small overlaps and short gaps.
    const nearby = next.start <= cur.end + maxGap && next.start >= cur.start - 0.05;
    if (!sentenceEnd(cur.text) && nearby && span <= maxDuration && chars <= maxChars) {
      cur.text = (cur.text + " " + next.text).trim();
      if (next.end > cur.end) {
        cur.end = next.end;
      }
      cur.duration = cur.end - cur.start;
      continue;
    }
    out.push(cur);
    cur = { ...next };
  }
  out.push(cur);
  return enrichSegments(out);
}

export function buildTranscript(
  id: string,
  track: { languageCode: string; name: string; isAutoGenerated: boolean },
  segments: TranscriptSegment[],
  merged: boolean,
  translatedFrom: string,
  source: TranscriptSource | "",
  requestedLang: string,
  warnings: string[] | undefined,
): Transcript {
  const rawCount = segments.length;
  const finalSegments = merged ? mergeASRSegments(segments) : enrichSegments(segments);

  const lines: string[] = [];
  const textParts: string[] = [];
  let duration = 0;
  for (const s of finalSegments) {
    lines.push("[" + s.timestamp + "] " + s.text);
    textParts.push(s.text);
    if (s.end > duration) {
      duration = s.end;
    }
  }

  let name = track.name;
  if (translatedFrom !== "") {
    name = name + " (translated to " + track.languageCode + ")";
  }
  let resolvedSource: TranscriptSource | "" = source;
  if (resolvedSource === "") {
    resolvedSource = track.isAutoGenerated ? "asr" : "manual";
    if (translatedFrom !== "") {
      resolvedSource = "translated";
    }
  }

  // Key order mirrors the Go struct so serialized output is byte-comparable.
  return {
    videoId: id,
    languageCode: track.languageCode,
    languageName: name,
    requestedLang: requestedLang || undefined,
    resolvedLang: track.languageCode || undefined,
    source: resolvedSource || undefined,
    isAutoGenerated: track.isAutoGenerated,
    translatedFrom: translatedFrom || undefined,
    merged,
    rawSegmentCount: rawCount,
    segmentCount: finalSegments.length,
    durationSeconds: duration,
    segments: finalSegments,
    lines,
    text: textParts.join(" "),
    warnings: warnings && warnings.length > 0 ? warnings : undefined,
  };
}

export function soundTagOnly(text: string): boolean {
  return SOUND_TAG_PATTERN.test(text.trim());
}

export function stripSoundTagSegments(segments: TranscriptSegment[]): TranscriptSegment[] {
  return segments.filter((s) => !soundTagOnly(s.text.trim()));
}

export function groupSegmentsByChapters(
  videoId: string,
  segments: TranscriptSegment[],
  chapters: Chapter[],
): ChapterGroup[] {
  if (chapters.length === 0) {
    return [];
  }
  const groups: ChapterGroup[] = chapters.map((ch) => ({
    title: ch.title,
    startSeconds: ch.startSeconds,
    timestamp: ch.timestamp,
    url: watchUrlAt(videoId, ch.startSeconds),
    segments: [],
    text: "",
  }));
  for (const s of segments) {
    let idx = 0;
    for (let i = chapters.length - 1; i >= 0; i--) {
      if (s.start >= chapters[i]!.startSeconds) {
        idx = i;
        break;
      }
    }
    groups[idx]!.segments.push(s);
  }
  for (const group of groups) {
    group.text = group.segments.map((s) => s.text).join(" ");
  }
  return groups;
}

export function withTranscriptLang(baseUrl: string, lang: string): string {
  if (lang === "") {
    return baseUrl;
  }
  if (baseUrl.includes("tlang=")) {
    return baseUrl.replace(new RegExp(TLANG_PARAM_PATTERN.source, "g"), "tlang=" + lang);
  }
  const sep = baseUrl.includes("?") ? "&" : "?";
  return baseUrl + sep + "tlang=" + lang;
}

/**
 * Appends `pot=…&c=WEB` when YTUBE_PO_TOKEN is set. Caption GETs are
 * increasingly gated on BotGuard attestation; the player POST already carries
 * the token, but the timedtext URL often needs it too.
 */
export function withPOToken(baseUrl: string): string {
  const pot = env("YTUBE_PO_TOKEN");
  if (pot === "") {
    return baseUrl;
  }
  let sep = baseUrl.includes("?") ? "&" : "?";
  let out = baseUrl;
  if (!baseUrl.includes("pot=")) {
    out += sep + "pot=" + pot;
    sep = "&";
  }
  if (!out.includes("c=")) {
    out += sep + "c=WEB";
  }
  return out;
}

export function appendUniqueUrl(list: string[], u: string): string[] {
  if (u === "") {
    return list;
  }
  if (list.includes(u)) {
    return list;
  }
  return [...list, u];
}

function annotateStale(
  stale: { value: Transcript; ageSeconds: number },
  reason: string,
): Transcript {
  const transcript = { ...stale.value };
  transcript.stale = true;
  transcript.staleAgeSeconds = stale.ageSeconds;
  transcript.warnings = [
    ...(transcript.warnings ?? []),
    `Served stale transcript (${stale.ageSeconds}s old) — ${reason}`,
  ];
  return transcript;
}

