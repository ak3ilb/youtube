function parseIntOr0(value: string | undefined): number {
  if (!value) {
    return 0;
  }
  const n = Number.parseInt(value, 10);
  return Number.isFinite(n) ? n : 0;
}

export function parseLangChain(lang: string | undefined): string[] {
  const trimmed = (lang ?? "").trim();
  if (trimmed === "") {
    return [];
  }
  const out: string[] = [];
  const seen = new Set<string>();
  for (const part of trimmed.split(",")) {
    const p = part.trim().toLowerCase();
    if (p === "" || seen.has(p)) {
      continue;
    }
    seen.add(p);
    out.push(p);
  }
  return out;
}

export function langBase(code: string): string {
  const lower = code.toLowerCase();
  const i = lower.indexOf("-");
  return i > 0 ? lower.slice(0, i) : lower;
}

export function sourceOf(t: CaptionTrack): TranscriptSource {
  return t.isAutoGenerated ? "asr" : "manual";
}

