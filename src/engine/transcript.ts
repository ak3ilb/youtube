/** Go's `error.Error()` for ExtractError is "CODE: message"; mirror that. */
export function errorText(err: unknown): string {
  if (isExtractError(err)) {
    return `${err.code}: ${err.message}`;
  }
  if (err instanceof Error) {
    return err.message;
  }
  return String(err);
}

/** Reports whether a failure is worth rescuing from stale cache. */
export function isRetryableExtract(err: unknown): boolean {
  if (err === null || err === undefined) {
    return false;
  }
  if (!isExtractError(err)) {
    return true;
  }
  switch (err.code) {
    case "RATE_LIMITED":
    case "RATE_BUDGET_EXCEEDED":
    case "NETWORK_ERROR":
    case "TIMEOUT":
    case "EMPTY_TRANSCRIPT":
    case "CAPTION_PARSE_ERROR":
    case "YOUTUBE_HTTP_ERROR":
    case "ACCESS_DENIED":
      return true;
    default:
      return err.retryable;
  }
}

