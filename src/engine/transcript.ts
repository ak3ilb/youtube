export function classifyPlayabilityFailure(videoId: string, attempts: string[]): ExtractError {
  const joined = attempts.join(" | ").toLowerCase();
  let code = "VIDEO_UNAVAILABLE";
  let message = "YouTube did not return a playable response for this video";
  let retryable = false;
  if (joined.includes("login_required") || joined.includes("sign in") || joined.includes("age")) {
    code = "AUTH_REQUIRED";
    message =
      "This video requires sign-in or age verification; pass cookies via --cookies or YTUBE_COOKIES";
  } else if (joined.includes("private")) {
    code = "PRIVATE_VIDEO";
    message = "This video is private";
  } else if (joined.includes("unavailable") || joined.includes("removed")) {
    code = "VIDEO_UNAVAILABLE";
    message = "This video is unavailable (deleted, region-blocked, or the ID does not exist)";
  } else if (joined.includes("rate") || joined.includes("429")) {
    code = "RATE_LIMITED";
    retryable = true;
    message = "YouTube rate-limited the request; wait a few minutes and retry";
  } else if (joined.includes("live")) {
    code = "LIVE_NOT_SUPPORTED";
    message = "Live streams are not supported by this extractor";
  }
  return new ExtractError({
    code,
    message,
    retryable,
    details: { videoId, attempts },
  });
}

