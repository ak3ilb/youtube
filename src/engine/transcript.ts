/** Rewrites (or appends) the `fmt=` parameter of a timedtext URL. */
export function withFormat(baseUrl: string, format: string): string {
  if (FMT_PARAM_PATTERN.test(baseUrl)) {
    return baseUrl.replace(new RegExp(FMT_PARAM_PATTERN.source, "g"), "fmt=" + format);
  }
  return baseUrl + "&fmt=" + format;
}

/**
 * Parses srv1/srv3 timedtext XML without a DOM. YouTube's caption XML is flat
 * and machine-generated, so a scanning parser matches Go's `encoding/xml`
 * results for every shape the API emits.
 */
export function parseTimedTextXML(raw: string): TranscriptSegment[] {
  if (raw.includes("<transcript")) {
    const segments: TranscriptSegment[] = [];
    const pattern = /<text\b([^>]*?)(\/>|>([\s\S]*?)<\/text\s*>)/g;
    let match: RegExpExecArray | null;
    while ((match = pattern.exec(raw)) !== null) {
      const attrs = match[1] ?? "";
      const body = match[3] ?? "";
      const text = normalizeCaptionText(decodeCaptionBody(body));
      if (text === "") {
        continue;
      }
      segments.push({
        text,
        start: attrFloat(attrs, "start"),
        duration: attrFloat(attrs, "dur"),
        end: 0,
        timestamp: "",
        timestampEnd: "",
      });
    }
    return segments;
  }

  if (raw.includes("<timedtext")) {
    const bodyMatch = /<body\b[^>]*>([\s\S]*?)<\/body\s*>/.exec(raw);
    const bodyXml = bodyMatch?.[1] ?? "";
    const segments: TranscriptSegment[] = [];
    const pattern = /<p\b([^>]*?)(\/>|>([\s\S]*?)<\/p\s*>)/g;
    let match: RegExpExecArray | null;
    while ((match = pattern.exec(bodyXml)) !== null) {
      const attrs = match[1] ?? "";
      const inner = match[3] ?? "";
      // Go collects the paragraph's own chardata first, then each <s> span.
      const spans: string[] = [];
      const spanPattern = /<s\b[^>]*?(?:\/>|>([\s\S]*?)<\/s\s*>)/g;
      let spanMatch: RegExpExecArray | null;
      while ((spanMatch = spanPattern.exec(inner)) !== null) {
        spans.push(spanMatch[1] ?? "");
      }
      const ownText = inner.replace(spanPattern, "").replace(/<[^>]*>/g, "");
      const text = normalizeCaptionText(decodeCaptionBody(ownText + spans.join("")));
      if (text === "") {
        continue;
      }
      segments.push({
        text,
        start: attrFloat(attrs, "t") / 1000,
        duration: attrFloat(attrs, "d") / 1000,
        end: 0,
        timestamp: "",
        timestampEnd: "",
      });
    }
    return segments;
  }

  throw new ExtractError({
    code: "CAPTION_PARSE_ERROR",
    message: "YouTube returned an unrecognized caption format",
    retryable: true,
    details: { head: raw.slice(0, Math.min(120, raw.length)) },
  });
}
